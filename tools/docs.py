"""Generate and run the Optora documentation site."""

from __future__ import annotations

import argparse
import ast
import json
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

GENERATED_NOTICE = "<!-- Generated by tools.docs; do not edit manually. -->"
REPOSITORY_URL = "https://github.com/navidsharifi/optora/blob/main"
ORDER_PREFIX_RE = re.compile(r"^\d\d_(?P<name>\w+)$")
EXAMPLE_SCRIPTS = "[0-9][0-9]_*/[0-9][0-9]_*.py"
DISPLAY_NAMES = {
    "dro": "DRO",
    "dro_base": "DRO Base",
    "f_divergence": "f-Divergence",
    "group_dro": "Group DRO",
    "kl": "KL",
    "kl_dro": "KL-DRO",
    "mmd": "MMD",
    "mmd_dro": "MMD-DRO",
    "phi_dro": "Phi-DRO",
    "wasserstein_dro": "Wasserstein DRO",
}


def navigation_block(name: str) -> re.Pattern[str]:
    """Return the pattern of one generated block in the Zensical navigation."""
    return re.compile(
        rf"(?ms)^\s*# BEGIN GENERATED {name} NAVIGATION\n.*?"
        rf"^\s*# END GENERATED {name} NAVIGATION"
    )


API_NAVIGATION_RE = navigation_block("API")
EXAMPLES_NAVIGATION_RE = navigation_block("EXAMPLES")
EXAMPLES_OVERVIEW_INTRO = """\
Each example is one short script that shows one part of Optora. It runs
on a plain `pip install optora`, prints the numbers it computes and checks
them against a closed form or an independent computation, so a script that
runs to the end has verified its own output. CI runs every script on
Linux, macOS and Windows.

The scripts live under
[`examples/`](https://github.com/navidsharifi/optora/tree/main/examples)
in the repository, one folder per group. For longer experiments that
combine several components and discuss the results, see the
[Tutorials](../tutorials/index.md).

```bash
python examples/01_divergences/01_phi_divergences.py
```
"""
EXAMPLES_OVERVIEW_OUTRO = """\
## Adding an example

Put a numbered script into a numbered group folder, for example
`examples/02_ambiguity_sets/06_new_ball.py`. The first line of its module
docstring is the title, and the paragraph after it is the summary shown
above. `python -m tools.docs generate` then writes the page, this overview
and the sidebar entry, and `python -m tools.docs check` fails in CI until
they are regenerated.
"""


@dataclass(frozen=True, slots=True)
class ModuleDoc:
    """Metadata needed to generate one public module reference page."""

    import_path: str
    package_parts: tuple[str, ...]
    name: str
    symbols: tuple[str, ...]

    @property
    def relative_path(self) -> Path:
        """Return the module page path relative to the API docs root."""
        return Path(*self.documentation_parts, f"{self.name}.md")

    @property
    def documentation_parts(self) -> tuple[str, ...]:
        """Return the package path used in the generated documentation tree."""
        return self.package_parts or ("optora",)


def module_symbols(path: Path) -> tuple[str, ...]:
    """Return public classes and functions defined at a module's top level."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    definitions = (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
    return tuple(
        node.name
        for node in tree.body
        if isinstance(node, definitions) and not node.name.startswith("_")
    )


def discover_modules(package_root: Path) -> list[ModuleDoc]:
    """Return metadata for public Python modules under ``package_root``."""
    modules: list[ModuleDoc] = []
    for path in package_root.rglob("*.py"):
        if path.name == "__init__.py" or path.name.startswith("_"):
            continue
        relative = path.relative_to(package_root.parent).with_suffix("")
        modules.append(
            ModuleDoc(
                import_path=".".join(relative.parts),
                package_parts=relative.parts[1:-1],
                name=relative.name,
                symbols=module_symbols(path),
            )
        )
    return sorted(modules, key=lambda module: module.import_path)


def display_name(value: str) -> str:
    """Return a human-readable navigation label for a Python name."""
    return DISPLAY_NAMES.get(value, value.replace("_", " ").title())


def render_module_page(module: ModuleDoc) -> str:
    """Render one mkdocstrings page containing a module and its members."""
    return "\n".join(
        [
            GENERATED_NOTICE,
            "",
            f"# `{module.import_path}`",
            "",
            f"::: {module.import_path}",
            "    options:",
            "      members_order: source",
            "      show_root_heading: false",
            "      show_root_toc_entry: false",
            "",
        ]
    )


def render_package_index(
    package_parts: tuple[str, ...], modules: list[ModuleDoc]
) -> str:
    """Render an index linking all modules in one subpackage."""
    package_name = ".".join(("optora", *package_parts))
    sections = [
        GENERATED_NOTICE,
        "",
        f"# `{package_name}`",
        "",
        "## Modules",
    ]
    for module in modules:
        sections.append(f"- [`{module.import_path}`]({module.name}.md)")
        for symbol in module.symbols:
            anchor = f"{module.name}.md#{module.import_path}.{symbol}"
            sections.append(f"    - [`{symbol}`]({anchor})")
    return "\n".join(sections) + "\n"


def group_modules(modules: list[ModuleDoc]) -> dict[tuple[str, ...], list[ModuleDoc]]:
    """Group discovered modules by their owning subpackage."""
    grouped: dict[tuple[str, ...], list[ModuleDoc]] = defaultdict(list)
    for module in modules:
        grouped[module.package_parts].append(module)
    return grouped


def render_api_overview(modules: list[ModuleDoc]) -> str:
    """Render the API landing page as a card grid of subpackages."""
    lines = [
        "---",
        "icon: lucide/book-open",
        "---",
        "",
        GENERATED_NOTICE,
        "",
        "# API reference",
        "",
        "Generated from the source docstrings. Each subpackage lists its",
        "modules, and every module page documents the classes and functions it",
        "defines.",
        "",
        '<div class="grid cards" markdown>',
        "",
    ]
    for package_parts, package_modules in sorted(group_modules(modules).items()):
        package_name = ".".join(("optora", *package_parts))
        package_path = "/".join(package_modules[0].documentation_parts)
        names = ", ".join(f"`{module.name}`" for module in package_modules)
        lines.extend(
            [
                f"-   :material-package-variant:{{ .lg .middle }} __`{package_name}`__",
                "",
                "    ---",
                "",
                f"    {names}",
                "",
                f"    [:octicons-arrow-right-24: Browse]({package_path}/index.md)",
                "",
            ]
        )
    lines.append("</div>")
    return "\n".join(lines) + "\n"


def render_api_navigation(modules: list[ModuleDoc]) -> str:
    """Render hierarchical Zensical navigation for generated API pages."""
    grouped = group_modules(modules)

    lines = ["  # BEGIN GENERATED API NAVIGATION", '  { "API reference" = [']
    lines.append('    { "Overview" = "api/index.md" },')
    for package_parts, package_modules in sorted(grouped.items()):
        documentation_parts = package_modules[0].documentation_parts
        package_path = "/".join(documentation_parts)
        package_label = display_name(package_parts[-1]) if package_parts else "Optora"
        lines.append(f'    {{ "{package_label}" = [')
        lines.append(f'      {{ "Overview" = "api/{package_path}/index.md" }},')
        for module in package_modules:
            path = module.relative_path.as_posix()
            lines.append(f'      {{ "{display_name(module.name)}" = "api/{path}" }},')
        lines.append("    ] },")
    lines.extend(["  ] },", "  # END GENERATED API NAVIGATION"])
    return "\n".join(lines)


@dataclass(frozen=True, slots=True)
class ExampleDoc:
    """Metadata needed to generate one example page from its script."""

    script: str
    group: str
    name: str
    title: str
    summary: str

    @property
    def relative_path(self) -> Path:
        """Return the example page path relative to the examples docs root."""
        return Path(self.group, f"{self.name}.md")

    @property
    def group_label(self) -> str:
        """Return the sentence-case navigation label of the example's group."""
        return self.group.replace("_", " ").capitalize()


def strip_order_prefix(name: str) -> str:
    """Return `name` without its two-digit order prefix, such as `01_`."""
    match = ORDER_PREFIX_RE.match(name)
    if match is None:
        raise ValueError(f"{name!r} must start with a two-digit prefix such as '01_'")
    return match.group("name")


def discover_examples(examples_root: Path) -> list[ExampleDoc]:
    """Return metadata for the numbered example scripts in their sidebar order.

    Each script sits in a numbered group folder. The first line of its
    module docstring is the title, and the rest of the docstring is the
    summary.
    """
    examples: list[ExampleDoc] = []
    for path in sorted(examples_root.glob(EXAMPLE_SCRIPTS)):
        docstring = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
        if not docstring:
            raise ValueError(f"{path} needs a module docstring with a title")
        title, _, summary = docstring.partition("\n")
        examples.append(
            ExampleDoc(
                script=path.relative_to(examples_root.parent).as_posix(),
                group=strip_order_prefix(path.parent.name),
                name=strip_order_prefix(path.stem),
                title=title.strip().removesuffix("."),
                summary=summary.strip(),
            )
        )
    return examples


def group_examples(examples: list[ExampleDoc]) -> dict[str, list[ExampleDoc]]:
    """Group examples by their group folder, keeping the discovery order."""
    grouped: dict[str, list[ExampleDoc]] = {}
    for example in examples:
        grouped.setdefault(example.group, []).append(example)
    return grouped


def render_example_page(example: ExampleDoc) -> str:
    """Render one example page: summary, run command and the full script."""
    return "\n".join(
        [
            GENERATED_NOTICE,
            "",
            f"# {example.title}",
            "",
            example.summary,
            "",
            "Run it from the repository root. It needs nothing beyond `optora`",
            "and PyTorch.",
            "",
            "```bash",
            f"python {example.script}",
            "```",
            "",
            f'```py title="{example.script}"',
            f'--8<-- "{example.script}"',
            "```",
            "",
            f"[View the script on GitHub]({REPOSITORY_URL}/{example.script})",
            "",
        ]
    )


def render_examples_overview(examples: list[ExampleDoc]) -> str:
    """Render the examples landing page with one table per group."""
    lines = [
        "---",
        "icon: lucide/code",
        "---",
        "",
        GENERATED_NOTICE,
        "",
        "# Examples",
        "",
        EXAMPLES_OVERVIEW_INTRO,
    ]
    for group_members in group_examples(examples).values():
        lines.extend(
            [
                f"## {group_members[0].group_label}",
                "",
                "| Example | What it shows |",
                "| --- | --- |",
            ]
        )
        for example in group_members:
            summary = " ".join(example.summary.split())
            path = example.relative_path.as_posix()
            lines.append(f"| [{example.title}]({path}) | {summary} |")
        lines.append("")
    lines.append(EXAMPLES_OVERVIEW_OUTRO)
    return "\n".join(lines)


def render_examples_navigation(examples: list[ExampleDoc]) -> str:
    """Render the Zensical navigation of the examples, grouped by folder."""
    lines = ["  # BEGIN GENERATED EXAMPLES NAVIGATION", '  { "Examples" = [']
    lines.append('    { "Overview" = "examples/index.md" },')
    for group_members in group_examples(examples).values():
        lines.append(f"    {{ {json.dumps(group_members[0].group_label)} = [")
        for example in group_members:
            path = f"examples/{example.relative_path.as_posix()}"
            lines.append(
                f"      {{ {json.dumps(example.title)} = {json.dumps(path)} }},"
            )
        lines.append("    ] },")
    lines.extend(["  ] },", "  # END GENERATED EXAMPLES NAVIGATION"])
    return "\n".join(lines)


def replace_navigation(
    config: str, pattern: re.Pattern[str], navigation: str, name: str
) -> str:
    """Replace the one generated navigation block matching `pattern`."""
    updated, count = pattern.subn(lambda _: navigation, config)
    if count != 1:
        raise RuntimeError(f"zensical.toml must contain one generated {name} nav block")
    return updated


def write_if_changed(path: Path, content: str) -> None:
    """Write generated content only when it differs from the existing file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8")


GENERATED_ROOTS = (Path("docs", "api"), Path("docs", "examples"))


def stale_generated_pages(root: Path, expected: set[Path]) -> list[Path]:
    """Return obsolete pages owned by this generator."""
    return sorted(
        path
        for generated_root in GENERATED_ROOTS
        for path in (root / generated_root).rglob("*.md")
        if path not in expected
        and path.read_text(encoding="utf-8").startswith(GENERATED_NOTICE)
    )


def render_documentation(root: Path) -> dict[Path, str]:
    """Render every generator-owned file, including Zensical navigation.

    The API reference is generated from `optora/`. The examples section is
    generated from `examples/` when that folder exists.
    """
    modules = discover_modules(root / "optora")
    api_root = root / "docs" / "api"

    pages: dict[Path, str] = {api_root / "index.md": render_api_overview(modules)}
    for package_parts, package_modules in group_modules(modules).items():
        package_root = api_root.joinpath(*package_modules[0].documentation_parts)
        pages[package_root / "index.md"] = render_package_index(
            package_parts, package_modules
        )
        for module in package_modules:
            pages[api_root / module.relative_path] = render_module_page(module)

    config_path = root / "zensical.toml"
    config = replace_navigation(
        config_path.read_text(encoding="utf-8"),
        API_NAVIGATION_RE,
        render_api_navigation(modules),
        "API",
    )

    if (root / "examples").is_dir():
        examples = discover_examples(root / "examples")
        examples_root = root / "docs" / "examples"
        pages[examples_root / "index.md"] = render_examples_overview(examples)
        for example in examples:
            pages[examples_root / example.relative_path] = render_example_page(example)
        config = replace_navigation(
            config,
            EXAMPLES_NAVIGATION_RE,
            render_examples_navigation(examples),
            "EXAMPLES",
        )

    pages[config_path] = config
    return pages


def generate_documentation(root: Path) -> list[Path]:
    """Generate the API reference, the example pages and their navigation."""
    pages = render_documentation(root)
    for path in stale_generated_pages(root, set(pages)):
        path.unlink()
    for path, content in pages.items():
        write_if_changed(path, content)
    return sorted(pages)


def outdated_documentation(root: Path) -> list[Path]:
    """Return generator-owned files that differ from freshly rendered output."""
    pages = render_documentation(root)
    outdated = {
        path
        for path, content in pages.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    }
    outdated.update(stale_generated_pages(root, set(pages)))
    return sorted(outdated)


def zensical_executable() -> str:
    """Return the Zensical launcher installed beside the active Python."""
    executable_name = "zensical.exe" if sys.platform == "win32" else "zensical"
    executable = Path(sys.executable).with_name(executable_name)
    return str(executable) if executable.exists() else "zensical"


def build_parser() -> argparse.ArgumentParser:
    """Build the documentation command-line parser."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root. Defaults to this script's parent repository.",
    )
    parser.add_argument(
        "command",
        choices=("generate", "check", "build", "serve"),
        help=(
            "Generate the API and example pages, check them for staleness, "
            "build the site, or serve with live reload."
        ),
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Generate the documentation pages and optionally invoke Zensical."""
    args = build_parser().parse_args(argv)
    root = args.root.resolve()

    if args.command == "check":
        outdated = outdated_documentation(root)
        for path in outdated:
            print(f"Outdated: {path.relative_to(root).as_posix()}")
        if outdated:
            print("Run 'python -m tools.docs generate' and commit the result.")
            return 1
        print("Generated documentation is up to date")
        return 0

    generated = generate_documentation(root)
    print(f"Generated {len(generated)} documentation files")

    if args.command == "generate":
        return 0

    command = [zensical_executable(), args.command]
    if args.command == "build":
        command.append("--clean")
    return subprocess.run(command, cwd=root, check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
